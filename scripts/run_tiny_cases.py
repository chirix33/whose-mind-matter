"""Stage 1 smallest examples: exact symbolic-oracle labels + a replayed episode per tiny case.

Run (CPU only):
    python scripts/run_tiny_cases.py [--seed 0]

Writes $OFFICEMINDS_RUNS/tiny/<run_id>/{manifest.json,labels.json,episodes.jsonl}
and the human-readable table reports/tiny-cases.md (regenerated; cites the run id).
"""

from __future__ import annotations

import argparse
import json
import os
import sys
from dataclasses import asdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from officeminds.episode import VisibleHistory, episode_record, replay, run_episode, sample_params  # noqa: E402
from officeminds.scenarios import TINY_CASES  # noqa: E402
from vomi import runlog  # noqa: E402
from vomi.oracle import ExactOracle, brute_force_best_return  # noqa: E402
from vomi.units import generate_candidates  # noqa: E402


def oracle_policy(sc):
    """Bayes-optimal visible-only policy (no mental units): recomputes the exact belief each step."""

    def policy(hist: VisibleHistory):
        o = ExactOracle(sc, hist)
        return o.best_action(o.belief, o.obs)

    return policy


def analyze(case: str, seed: int) -> tuple[dict, dict]:
    sc = TINY_CASES[case]()
    params = sample_params(sc, seed)
    w = sc.build(params)
    hist = VisibleHistory(sc.brief, [(None, w.reset())])
    o = ExactOracle(sc, hist)
    units = generate_candidates(sc.config, hist)
    labels = o.allocation_labels(units)
    full_info = sum(p * brute_force_best_return(x, o.obs) for p, x in o.belief)
    d_star = o.effective_depth(units)
    reports = {}
    for cont in ("retain", "drop"):
        reports[cont] = [asdict(o.unit_report(u, continuation=cont)) for u in units]
    pruned = sum(r["p_flip"] == 0 and abs(r["delta_j"]) < 1e-12 for r in reports["retain"])

    ep_hist, trace, _ = run_episode(sc, params, oracle_policy(sc))
    rec = episode_record(ep_hist, trace)
    replay_ok = replay(json.loads(json.dumps(rec)), TINY_CASES) == rec

    row = {
        "case": case,
        "purpose": sc.purpose,
        "n_consistent_worlds": len(o.worlds),
        "candidates": [str(u) for u in units],
        "j_empty": labels.j_empty,
        "j_all_candidates": labels.j_full,
        "full_information_bound": full_info,
        "effective_depth": d_star,
        "indistinguishable_pairs_below_dstar": len(o.indistinguishable_pairs(units, d_star)) if d_star > 0 else 0,
        "labels": asdict(labels),
        "unit_reports": reports,
        "p1_prunable_units": pruned,
        "episode": {"seed": seed, "params": dict(params), "actions": [str(a) for a in ep_hist.actions],
                    "return": rec["return"], "outcome": ep_hist.last.outcome, "replay_identical": replay_ok},
    }
    return row, rec


def markdown(rows: list[dict], run_id: str) -> str:
    out = [
        "# Tiny-case exact symbolic-oracle labels",
        "",
        f"Generated by `scripts/run_tiny_cases.py`, run `{run_id}` (manifest under `$OFFICEMINDS_RUNS/tiny/{run_id}/`).",
        "Label type: exact symbolic-oracle values (exhaustive enumeration; no LLM involved). Continuation `retain` unless noted.",
        "",
        "| case | worlds | J(∅) | J(all cand.) | full-info bound | ℓ* | minimal sufficient sets | LOO-necessary | episode (seeded) | replay |",
        "|---|---|---|---|---|---|---|---|---|---|",
    ]
    for r in rows:
        ms = "; ".join("{" + ", ".join(s) + "}" for s in r["labels"]["minimal_sufficient"])
        ep = r["episode"]
        out.append(
            f"| {r['case']} | {r['n_consistent_worlds']} | {r['j_empty']:.4f} | {r['j_all_candidates']:.4f} | "
            f"{r['full_information_bound']:.4f} | {r['effective_depth']} | {ms} | "
            f"{', '.join(r['labels']['loo_necessary']) or '—'} | {ep['outcome']} {ep['return']:+.2f} | "
            f"{'identical' if ep['replay_identical'] else 'MISMATCH'} |"
        )
    out += ["", "## Per-unit singleton reports (S = ∅)", "",
            "| case | unit | ΔJ retain | P(flip) | E[ΔQ|flip] | no-flip residual | ΔJ drop | H(c_u) bits |",
            "|---|---|---|---|---|---|---|---|"]
    for r in rows:
        for ret, drp in zip(r["unit_reports"]["retain"], r["unit_reports"]["drop"]):
            out.append(
                f"| {r['case']} | {ret['unit']} | {ret['delta_j']:.4f} | {ret['p_flip']:.3f} | {ret['dq_given_flip']:.4f} | "
                f"{ret['no_flip_residual']:.4f} | {drp['delta_j']:.4f} | {ret['content_entropy_bits']:.3f} |"
            )
    return "\n".join(out) + "\n"


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--seed", type=int, default=0)
    args = ap.parse_args()
    manifest = runlog.new_manifest("tiny", {"cases": sorted(TINY_CASES), "seed": args.seed})
    out = Path(os.environ.get("OFFICEMINDS_RUNS", Path.home() / "officeminds-runs")) / "tiny" / manifest["run_id"]
    out.mkdir(parents=True, exist_ok=True)
    rows = []
    with (out / "episodes.jsonl").open("w") as f:
        for case in TINY_CASES:
            row, rec = analyze(case, args.seed)
            rows.append(row)
            f.write(json.dumps(rec) + "\n")
    (out / "labels.json").write_text(json.dumps(rows, indent=2))
    (ROOT / "reports" / "tiny-cases.md").write_text(markdown(rows, manifest["run_id"]), encoding="utf-8")
    path = runlog.finish(manifest, out, all_replays_identical=all(r["episode"]["replay_identical"] for r in rows))
    for r in rows:
        print(f"{r['case']:<22} J0={r['j_empty']:.4f} JU={r['j_all_candidates']:.4f} l*={r['effective_depth']} "
              f"min={r['labels']['minimal_sufficient']} replay={r['episode']['replay_identical']}")
    print(f"manifest: {path}")


if __name__ == "__main__":
    main()
